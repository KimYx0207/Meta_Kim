export function translateAgentUi(value, language = "zh") {
  const text = typeof value === "string" ? value : String(value ?? "");
  if (!text || !language || language === "zh" || language.startsWith("zh")) return text;
  const lang = language.startsWith("ja") ? "ja" : language.startsWith("ko") ? "ko" : "en";
  const dict = LIVE_AGENT_UI_DICTIONARY[lang];
  if (!dict) return text;
  if (Object.prototype.hasOwnProperty.call(dict, text)) return dict[text];
  const trimmed = text.trim();
  if (Object.prototype.hasOwnProperty.call(dict, trimmed)) return dict[trimmed];
  for (const [pattern, table] of LIVE_AGENT_UI_PATTERNS) {
    const template = table[lang];
    if (!template) continue;
    const match = trimmed.match(new RegExp(pattern, "u"));
    if (!match) continue;
    return template.replace(/\{(\d+)\}/gu, (_, index) => {
      const captured = match[Number(index) + 1] ?? "";
      return translateAgentUi(captured, lang);
    });
  }
  if (trimmed.includes(" · ")) {
    const parts = trimmed.split(" · ");
    const mapped = parts.map((part) => translateAgentUi(part, lang));
    if (mapped.some((item, idx) => item !== parts[idx])) return mapped.join(" · ");
  }
  return text;
}

export function serializeLiveAgentCopy() {
  const safeJson = (val) => JSON.stringify(val).replaceAll("<", "\\u003c");
  return `const LIVE_AGENT_UI_DICTIONARY = ${safeJson(LIVE_AGENT_UI_DICTIONARY)};\nconst LIVE_AGENT_UI_PATTERNS = ${safeJson(LIVE_AGENT_UI_PATTERNS)};\n${translateAgentUi.toString()}`;
}
